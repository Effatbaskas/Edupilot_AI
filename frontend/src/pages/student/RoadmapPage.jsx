import { useEffect, useState } from 'react'
import { AlertCircle, CalendarDays, Check, Circle, Clock3, Compass, Flag, Loader2, Sparkles, Target } from 'lucide-react'
import DemoNotice from '../../components/DemoNotice'
import { roadmapService } from '../../services/roadmapService'

export default function RoadmapPage() {
  const [roadmap, setRoadmap] = useState(null)
  const [tasks, setTasks] = useState([])
  const [examDate, setExamDate] = useState('')
  const [dailyHours, setDailyHours] = useState(2)
  const [targetScore, setTargetScore] = useState(80)
  const [weakTopics, setWeakTopics] = useState('')
  const [loading, setLoading] = useState(true)
  const [saving, setSaving] = useState('')
  const [error, setError] = useState('')
  const doneCount = tasks.filter((task) => task.status === 'completed').length

  useEffect(() => {
    roadmapService.getRoadmap().then((data) => {
      const saved = data.roadmap || (data.tasks ? data : null)
      setRoadmap(saved)
      setTasks(saved?.tasks || [])
    }).catch((requestError) => {
      setError(requestError.response?.data?.error || requestError.response?.data?.detail || 'Could not load your study plan.')
    }).finally(() => setLoading(false))
  }, [])

  async function generateRoadmap(event) {
    event.preventDefault()
    setSaving('generate')
    setError('')
    try {
      const saved = await roadmapService.generateRoadmap({
        exam_date: examDate || null, daily_hours: Number(dailyHours), target_score: Number(targetScore),
        weak_topics: weakTopics.split(',').map((topic) => topic.trim()).filter(Boolean),
      })
      setRoadmap(saved)
      setTasks(saved.tasks || [])
    } catch (requestError) {
      setError(requestError.response?.data?.error || requestError.response?.data?.detail || 'Could not generate a study plan.')
    } finally {
      setSaving('')
    }
  }

  async function toggleTask(task) {
    const status = task.status === 'completed' ? 'pending' : 'completed'
    setSaving(task.id)
    setError('')
    try {
      const updated = await roadmapService.updateTask(task.id, status)
      setTasks((current) => current.map((item) => item.id === task.id ? { ...item, ...updated } : item))
    } catch (requestError) {
      setError(requestError.response?.data?.error || requestError.response?.data?.detail || 'Could not update this task.')
    } finally {
      setSaving('')
    }
  }

  return <div className="feature-page">
    <div className="feature-intro"><div><span className="eyebrow">A PLAN THAT CAN BEND</span><h2>One step at a time.</h2><p>A friendly outline for your next few study sessions.</p></div><span className="feature-hero-icon roadmap-hero-icon"><Compass size={24} /></span></div>
    <DemoNotice>This roadmap is generated by backend rules, saved to your account, and is not an AI-generated plan.</DemoNotice>
    {error && <div className="error-alert" role="alert"><AlertCircle size={17} />{error}</div>}
    {loading ? <section className="panel admin-loading"><Loader2 className="spin-icon" size={21} /> Loading your saved plan…</section> : !roadmap ? <form className="panel quiz-start" onSubmit={generateRoadmap}>
      <span className="quiz-start-icon"><CalendarDays size={25} /></span><span className="soft-tag">PERSONALIZED RULE-BASED PLAN</span><h3>Make a study plan</h3><p>Set your study time and exam date. Recorded quiz results help prioritize topics you may want to revisit.</p>
      <label>Exam date (optional)<input className="input-field" type="date" value={examDate} onChange={(event) => setExamDate(event.target.value)} min={new Date().toISOString().slice(0, 10)} /></label>
      <div className="quiz-meta"><label>Daily study hours<input className="input-field" type="number" min="0.25" max="12" step="0.25" value={dailyHours} onChange={(event) => setDailyHours(event.target.value)} required /></label><label>Target score %<input className="input-field" type="number" min="0" max="100" value={targetScore} onChange={(event) => setTargetScore(event.target.value)} /></label></div>
      <label>Topics to include (comma separated, optional)<input className="input-field" value={weakTopics} onChange={(event) => setWeakTopics(event.target.value)} placeholder="Biology, algebra" /></label>
      <button className="button button-dark" type="submit" disabled={saving === 'generate'}>{saving === 'generate' ? <Loader2 className="spin-icon" size={16} /> : <Sparkles size={16} />}{saving === 'generate' ? 'Creating plan…' : 'Generate my plan'} <ArrowRight size={16} /></button>
    </form> : <>
      <div className="roadmap-summary panel"><div className="roadmap-summary-main"><span className="roadmap-calendar"><CalendarDays size={19} /></span><div><small>YOUR STUDY FOCUS</small><h3>{tasks[0]?.topic || 'Your learning plan'}</h3><p>Rule-based plan · {roadmap.daily_hours} hours per day{roadmap.exam_date ? ` · Exam ${new Date(`${roadmap.exam_date}T00:00:00`).toLocaleDateString()}` : ''}</p></div></div><div className="roadmap-completion"><strong>{doneCount}<small> / {tasks.length}</small></strong><span>steps completed</span><div className="mini-progress"><i style={{ width: `${tasks.length ? doneCount / tasks.length * 100 : 0}%` }} /></div></div></div>
      <div className="roadmap-layout"><section className="roadmap-list"><div className="roadmap-list-heading"><div><h3>Your upcoming steps</h3><p>Progress is saved to your account.</p></div><button className="button button-outline button-small" onClick={() => setRoadmap(null)}><Sparkles size={14} /> Adjust plan</button></div>{tasks.map((task, index) => { const done = task.status === 'completed'; return <article className={`roadmap-task ${done ? 'task-done' : ''}`} key={task.id}><div className="task-timeline"><span className={`task-check ${done ? 'checked' : ''}`}><button disabled={saving === task.id} onClick={() => toggleTask(task)} aria-label={done ? 'Mark as not done' : 'Mark step done'}>{saving === task.id ? <Loader2 className="spin-icon" size={14} /> : done ? <Check size={15} /> : <Circle size={17} />}</button></span>{index < tasks.length - 1 && <i />}</div><div className="task-body"><div className="task-day">DAY {task.day_number}<span>{task.priority} priority</span></div><div className="task-card"><div className="task-card-top"><span className={`task-type type-${task.task_type}`}>{task.task_type}</span><span><Clock3 size={13} /> {task.duration_minutes} min</span></div><h4>{task.topic}</h4><p>{task.description || task.subject || ''}</p></div></div></article>})}</section>
        <aside className="roadmap-side"><div className="tip-panel"><span className="tip-panel-icon"><Target size={19} /></span><small>HOW THIS PLAN IS BUILT</small><h3>Small steps first.</h3><p>{roadmap.prioritization_explanation}</p></div><div className="goal-panel"><span className="goal-icon"><Flag size={17} /></span><div><small>PLAN LENGTH</small><strong>{roadmap.total_days || tasks.length} study days</strong><p>Saved to your account</p></div></div></aside>
      </div>
    </>}
  </div>
}
